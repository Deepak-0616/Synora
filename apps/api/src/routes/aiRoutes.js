import { Router } from "express";
import { authenticateToken } from "../middleware/auth.js";
import * as aiCtrl from "../controllers/aiController.js";
const router = Router();
router.use(authenticateToken);
router.post("/classify", aiCtrl.classifyText);
router.post("/duplicates", aiCtrl.checkDuplicates);
router.post("/summarize", aiCtrl.summarizeText);
router.get("/complaints/:id/risk", aiCtrl.getComplaintRisk);
export default router;
